// The simulated set as data for the desktop gate's simulator
// (src-tauri/src/prolink_sim.rs): the crate it plays, and a timeline of this
// Auto DJ's decks that the Rust one must reproduce (its drift guard). The
// file is tests/fixtures/dj-sim.json; after a change to the crate or the
// Auto DJ, regenerate it with
//
//   EMPYREAN_UPDATE_FIXTURES=1 bun test src/runtime/djlink.fixture.test.ts

import { expect, test } from "bun:test";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { CRATE, DjLinkSim, SET_BPM } from "./djlink";

const FIXTURE = join(import.meta.dir, "..", "..", "..", "..", "tests", "fixtures", "dj-sim.json");

/** Seconds of set in the timeline: more than one pass through the crate. */
const SECONDS = 600;

const r6 = (v: number) => Math.round(v * 1e6) / 1e6;

function fixture(): string {
  const sim = new DjLinkSim();
  const timeline: unknown[] = [];
  for (let frame = 1; frame <= SECONDS * 60; frame++) {
    sim.step(1 / 60);
    if (frame % 60 !== 0) continue;
    const s = sim.state();
    timeline.push([
      frame,
      s.decks.find((d) => d.master)!.player,
      r6(s.crossfader),
      ...s.decks.map((d) => [d.track, d.mode, d.beat, r6(d.fader), d.loopBeats ?? 0]),
    ]);
  }
  const lines = [
    "{",
    `  "comment": "Generated by packages/patch-web/src/runtime/djlink.fixture.test.ts; read by src-tauri/src/prolink_sim.rs. timeline rows: [frame at 60 Hz, master player, crossfader, [track, mode, beat, fader, loop beats] for deck 1, the same for deck 2].",`,
    `  "bpm": ${SET_BPM},`,
    `  "crate": ${JSON.stringify(CRATE, null, 2).replace(/\n/g, "\n  ")},`,
    `  "timeline": [`,
    timeline.map((row) => `    ${JSON.stringify(row)}`).join(",\n"),
    "  ]",
    "}",
    "",
  ];
  return lines.join("\n");
}

test("tests/fixtures/dj-sim.json is this simulator's crate and timeline", () => {
  const want = fixture();
  if (process.env.EMPYREAN_UPDATE_FIXTURES) writeFileSync(FIXTURE, want);
  expect(existsSync(FIXTURE)).toBe(true);
  const have = readFileSync(FIXTURE, "utf8").replace(/\r\n/g, "\n");
  // Stale: EMPYREAN_UPDATE_FIXTURES=1 bun test src/runtime/djlink.fixture.test.ts
  expect(have).toBe(want);
});
